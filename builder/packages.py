"""Package selection for bootstrap, chroot, and live images."""

from __future__ import annotations

from typing import List

from builder.config import TideConfig


class PackagePlan:
    def __init__(self, config: TideConfig, profile: str = "") -> None:
        self.config = config
        self.profile = profile

    def bootstrap_packages(self) -> List[str]:
        """Small set installed by debootstrap before the chroot is configured."""
        packages = [
            "systemd",
            "systemd-sysv",
            "sudo",
            "ca-certificates",
            "locales",
            "tzdata",
            "apt",
            "bash",
            "coreutils",
        ]
        return sorted(set(packages + self.config.base_packages))

    def install_packages(self) -> List[str]:
        """All packages installed during chroot configuration or live-build."""
        return self.config.packages(self.profile)

    def package_list_text(self) -> str:
        header = (
            "# Generated by the Tide build system. Do not edit by hand.\n"
            f"# Profile: {self.profile or 'none'}\n"
        )
        return header + "\n".join(self.install_packages()) + "\n"
